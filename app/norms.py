def norm(act, url, anchor, clause, quote, interpretation=None, strength="direct"):
    """strength: "direct" — the point itself requires/prohibits it; "interpretation" — derived from its meaning.
    `interpretation` explains how the point applies; for strength="interpretation" it says there is no direct rule."""
    return {"document": act, "clause": clause, "url": f"{url}#{anchor}" if anchor else url,
            "quote": quote, "interpretation": interpretation, "strength": strength}


