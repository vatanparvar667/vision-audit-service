def catalog_for_api() -> dict:
    return {"types": [{"id": k, "name": v["name"], "summary": v["summary"],
                       "norms": [{kk: n[kk] for kk in ("document", "clause", "url", "interpretation", "strength")}
                                 for n in v["norms"]]}
                      for k, v in VIOLATIONS.items()]}


def primary_norm(type_id: str) -> dict:
    n = VIOLATIONS[type_id]["norms"][0]
    return {k: n[k] for k in ("document", "clause", "url", "quote", "interpretation", "strength")}
